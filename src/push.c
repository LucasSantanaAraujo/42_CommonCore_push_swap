#include "push_swap.h"

static void	push(t_stack *src, t_stack *dst)
{
	int	i;

	if (src->size == 0)
		return ;
	i = dst->size;
	while (i > 0)
	{
		dst->data[i] = dst->data[i - 1];
		i--;
	}
	dst->data[0] = src->data[0];
	dst->size++;
	i = 0;
	while (i < src->size - 1)
	{
		src->data[i] = src->data[i + 1];
		i++;
	}
	src->size--;
}

void	pa(t_ps *ps)
{
	push(&ps->b, &ps->a);
	print_op(ps, PA);
}

void	pb(t_ps *ps)
{
	push(&ps->a, &ps->b);
	print_op(ps, PB);
}
